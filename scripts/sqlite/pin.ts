import { Database } from "bun:sqlite";
import { createHash } from "node:crypto";
import { resolve } from "node:path";
import { sqliteFingerprint } from "../../src/db/sqlite-runtime";

const tag = process.argv[2];
if (process.platform !== "linux" || tag !== `bun-v${Bun.version}`) {
  throw new Error("Run on Linux with the requested Bun installed: bun run sqlite:pin bun-v<Bun.version>");
}
async function download(path: string): Promise<string> {
  const response = await fetch(`https://raw.githubusercontent.com/oven-sh/bun/${tag}/${path}`);
  if (!response.ok) throw new Error(`Downloading ${path}: HTTP ${response.status}`);
  return response.text();
}
const [source, recipe] = await Promise.all([
  download("src/jsc/bindings/sqlite/sqlite3.c"),
  download("scripts/build/deps/sqlite.ts"),
]);
const block = recipe.match(/defines:\s*\{([^}]+)\}/)?.[1];
if (!block) throw new Error("Bun build recipe changed: inspect its SQLite defines before updating the pin");
const defines: Record<string, number> = {};
for (const line of block.replace(/\/\/[^\n]*/g, "").split("\n")) {
  if (!line.trim()) continue;
  const match = line.match(/^\s*(SQLITE_\w+):\s*(true|\d+),\s*$/);
  if (!match) throw new Error(`Unrecognized Bun SQLite define: ${line}`);
  const [, key, value] = match;
  if (!key || !value) throw new Error("Missing define name or value");
  defines[key] = value === "true" ? 1 : Number(value);
}
const version = source.match(/^#define SQLITE_VERSION\s+"([^"]+)"/m)?.[1];
const sourceId = source.match(/^#define SQLITE_SOURCE_ID\s+"([^"]+)"/m)?.[1];
using db = new Database(":memory:");
const runtime = sqliteFingerprint(db);
if (!version || !sourceId || runtime?.version !== version || runtime.sourceId !== sourceId) {
  throw new Error(`Bun ${Bun.version} does not match ${tag}'s SQLite source; install the matching Bun before pinning`);
}
const pin = {
  bunTag: tag, version, sourceId,
  source: { url: `https://raw.githubusercontent.com/oven-sh/bun/${tag}/src/jsc/bindings/sqlite/sqlite3.c`, sha256: createHash("sha256").update(source).digest("hex") },
  defines: Object.fromEntries(Object.entries(defines).sort(([a], [b]) => a.localeCompare(b))),
  compileOptions: runtime.compileOptions,
  darwinExtraCompileOptions: [],
};
await Bun.write(resolve(import.meta.dir, "../../src/db/sqlite-pin.ts"), `// Generated by bun run sqlite:pin ${tag}.\nexport const SQLITE_PIN = ${JSON.stringify(pin, null, 2)} as const;\n`);
