/**
 * Generates src/theme.css: Material Design 3 tonal color schemes (dark +
 * light) derived from a single seed color, mapped onto the app's semantic
 * design tokens.
 *
 * Usage: bun scripts/generate-theme.ts [#rrggbb]
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import {
  argbFromHex,
  type DynamicScheme,
  Hct,
  hexFromArgb,
  SchemeTonalSpot,
  type TonalPalette,
} from "@material/material-color-utilities";

const DEFAULT_SEED = "#756a9e";

const seed = (process.argv[2] ?? DEFAULT_SEED).toLowerCase();
if (!/^#[0-9a-f]{6}$/.test(seed)) {
  throw new Error(`Seed must be a #rrggbb hex color, got: ${seed}`);
}

// Semantic token → MD3 color role. Popovers sit above cards, so they take a
// higher surface-container step; borders use outline-variant (decorative)
// rather than outline (interactive emphasis).
function tokens(scheme: DynamicScheme): Record<string, string> {
  const hex = (argb: number) => hexFromArgb(argb);
  return {
    background: hex(scheme.surface),
    foreground: hex(scheme.onSurface),
    card: hex(scheme.surfaceContainerLow),
    "card-foreground": hex(scheme.onSurface),
    popover: hex(scheme.surfaceContainerHigh),
    "popover-foreground": hex(scheme.onSurface),
    primary: hex(scheme.primary),
    "primary-foreground": hex(scheme.onPrimary),
    secondary: hex(scheme.secondaryContainer),
    "secondary-foreground": hex(scheme.onSecondaryContainer),
    muted: hex(scheme.surfaceContainerHigh),
    "muted-foreground": hex(scheme.onSurfaceVariant),
    accent: hex(scheme.surfaceContainerHighest),
    "accent-foreground": hex(scheme.onSurface),
    destructive: hex(scheme.error),
    "destructive-foreground": hex(scheme.onError),
    border: hex(scheme.outlineVariant),
    input: hex(scheme.outlineVariant),
    ring: hex(scheme.primary),
  };
}

function declarations(scheme: DynamicScheme, indent: string): string {
  return Object.entries(tokens(scheme))
    .map(([name, value]) => `${indent}--color-${name}: ${value};`)
    .join("\n");
}

// Chart colors: series hues sampled from the scheme's tonal palettes for
// hue variety (primary/tertiary/secondary + darker variants, error last so
// index 5 is available for genuinely alarming series like heart rate).
function chartScheme(scheme: DynamicScheme, dark: boolean) {
  const tone = (palette: TonalPalette, t: number) => hexFromArgb(palette.tone(t));
  const main = dark ? 80 : 40;
  const alt = dark ? 60 : 30;
  return {
    palette: [
      tone(scheme.primaryPalette, main),
      tone(scheme.tertiaryPalette, main),
      tone(scheme.secondaryPalette, main),
      tone(scheme.primaryPalette, alt),
      tone(scheme.tertiaryPalette, alt),
      tone(scheme.errorPalette, main),
    ],
    text: hexFromArgb(scheme.onSurfaceVariant),
    axis: hexFromArgb(scheme.outlineVariant),
    split: hexFromArgb(scheme.surfaceContainerHigh),
    tooltipBg: hexFromArgb(scheme.surfaceContainerHigh),
    tooltipText: hexFromArgb(scheme.onSurface),
  };
}

const sourceHct = Hct.fromInt(argbFromHex(seed));
const dark = new SchemeTonalSpot(sourceHct, true, 0);
const light = new SchemeTonalSpot(sourceHct, false, 0);

const css = `/*
 * Generated by scripts/generate-theme.ts — do not edit by hand.
 * Seed: ${seed} (Material Design 3 tonal spot scheme, dark default).
 * Regenerate: bun scripts/generate-theme.ts [#rrggbb]
 */
@theme {
${declarations(dark, "  ")}
}

@media (prefers-color-scheme: light) {
  :root {
${declarations(light, "    ")}
  }
}
`;

const outPath = join(import.meta.dir, "..", "src", "theme.css");
writeFileSync(outPath, css);
console.log(`Wrote ${outPath} (seed ${seed})`);

const chartTs = `/*
 * Generated by scripts/generate-theme.ts — do not edit by hand.
 * Seed: ${seed}. Regenerate: bun scripts/generate-theme.ts [#rrggbb]
 */
export const chartSchemes = ${JSON.stringify({ dark: chartScheme(dark, true), light: chartScheme(light, false) }, null, 2)} as const;
`;
const chartOutPath = join(import.meta.dir, "..", "src", "lib", "chart-theme.generated.ts");
writeFileSync(chartOutPath, chartTs);
console.log(`Wrote ${chartOutPath}`);
