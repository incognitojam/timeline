/**
 * Convert legacy Google/Facebook PUA emoji codes to standard Unicode emoji.
 * These codes were used in Facebook Messenger exports from ~2010-2015.
 */
export function convertLegacyEmoji(text: string | null): string | null {
  if (!text) return text;

  let result = "";
  for (const char of text) {
    const cp = char.codePointAt(0);
    if (cp && cp >= 0xFE000 && cp <= 0xFFFFF) {
      result += GOOGLE_EMOJI_MAP[cp] ?? char;
    } else {
      result += char;
    }
  }
  return result;
}
